#include <stdio.h>

int main() {
    int idade = 42;             
float altura = 1.86f;       
double salario = 2500.75;   
char inicial = 'J';         
    printf("Idade: %d\n", idade);
    printf("Altura: %.2f\n", altura);
    printf("Salário: %.2lf\n", salario);
    printf("Inicial: %c\n", inicial);

    return 0;
}   

